// The changelog page is GENERATED from docs/releases/*.md (the single source
// of truth, which also feeds the GitHub release notes) so the two can never
// drift. Runs as pre{build,start}; the output is gitignored.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const releasesDir = join(here, '..', '..', 'docs', 'releases');
const out = join(here, '..', 'docs', 'changelog.md');

const versions = readdirSync(releasesDir)
  .filter((f) => /^\d+\.\d+\.\d+\.md$/.test(f))
  .map((f) => f.replace(/\.md$/, ''))
  .toSorted((a, b) => {
    const pa = a.split('.').map(Number);
    const pb = b.split('.').map(Number);
    return pb[0] - pa[0] || pb[1] - pa[1] || pb[2] - pa[2];
  });

const sections = versions.map((v) => {
  let body = readFileSync(join(releasesDir, `${v}.md`), 'utf-8');
  body = body.replace(/^# .*\n/, '').trim();
  // Repo-relative links do not resolve on the site: send known pages to
  // their site route and anything else to the repo on GitHub.
  body = body
    .replaceAll('](../getting-started.md)', '](/docs/getting-started)')
    .replaceAll('](../', '](https://github.com/appandflow/stim-cli/blob/main/docs/');
  // Demote headings one level under the version heading.
  body = body.replace(/^## /gm, '### ');
  return `## ${v}\n\n${body}`;
});

writeFileSync(
  out,
  `---
title: "Changelog"
sidebar_position: 99
description: "Release notes, generated from docs/releases/ -- the single source of truth"
---

{/* GENERATED by scripts/gen-changelog.mjs from ../docs/releases/*.md -- do not edit. */}

Full release history is also on [GitHub Releases](https://github.com/appandflow/stim-cli/releases).

${sections.join('\n\n')}
`,
);
console.log(`changelog: ${versions.length} releases -> docs/changelog.md`);
